--  24차 (선택): 기존 게시글의 잃어버린/주운 시각 KST 보정
--
--  배경: 2026-09-08 이전 코드는 datetime-local 입력을 서버(UTC) 기준으로
--  저장해서, 사용자가 고른 "한국 시각"이 9시간 어긋난 값으로 들어갔다.
--  (created_at 등 자동 타임스탬프는 정상 — 이 SQL 대상 아님.)
--
--  ⚠️ 딱 한 번만 실행할 것. 두 번 실행하면 18시간 어긋난다.
--  실행 전에 가장 최근 글 1~2개의 시각을 확인하고, 실행 후 다시 확인해
--  9시간 당겨졌는지 검증하세요.
-- ============================================================================

update lost_posts
set lost_at = lost_at - interval '9 hours'
where created_at < '2026-09-08T12:00:00Z';

update found_posts
set found_at = found_at - interval '9 hours'
where created_at < '2026-09-08T12:00:00Z';

